import { expect, test } from '@playwright/test';
import { readFile } from 'node:fs/promises';

test('review status is part of the existing record and older data remains intact', async ({ page }, info) => {
  await page.goto('/');
  await page.evaluate(() => {
    localStorage.setItem('nabd-al-injaz:assessment-tracking:v1', JSON.stringify([{id:'legacy-assessment', teacher:'معلم تجريبي', subject:'فيزياء', title:'اختبار قديم', grade:'9', submitted:true, analyzed:false, notes:'ملاحظات سابقة'}]));
    localStorage.setItem('nabd-al-injaz:short-tests:v1', JSON.stringify([{id:'old-review', teacher:'معلم تجريبي', subject:'فيزياء', title:'قديم', grade:'9', status:'بانتظار المراجعة', notes:'محتوى محفوظ', lessons:2, items:9, total:15, knowledge:6, application:6, reasoning:3, multipleChoice:3, longAnswer:1}]));
  });
  await page.reload();
  if (info.project.name === 'phone') await page.getByRole('button', {name:/عرض الأقسام/}).click();
  await page.getByRole('button', {name:'الاختبارات والتحصيل', exact:true}).click();
  const section = page.getByRole('region', {name:'متابعة الاختبارات والتحليل'});
  await expect(page.getByRole('region', {name:'مراجعة الاختبارات القصيرة'})).toHaveCount(0);
  await section.getByText('اختبار قديم · معلم تجريبي').click();
  await expect(section.getByText('مراجعة الاختبار: لم تُسجّل حالة المراجعة')).toBeVisible();
  await section.getByText('سجلات المراجعة السابقة (1)').click();
  await expect(section.getByText('ملاحظات: محتوى محفوظ')).toBeVisible();
  await section.getByRole('button', {name:'تعديل المتابعة'}).click();
  await expect(section.getByLabel('تمت مراجعة الاختبار')).not.toBeChecked();
  await section.getByLabel('تمت مراجعة الاختبار').check();
  await section.getByLabel('ملاحظات').fill('ملاحظات محدّثة');
  await section.getByRole('button', {name:'حفظ تعديل المتابعة'}).click();
  await expect(section.getByText('مراجعة الاختبار: تمت المراجعة')).toBeVisible();
  await expect(section.getByText('ملاحظات: ملاحظات محدّثة')).toBeVisible();
  expect(await page.evaluate(() => localStorage.getItem('nabd-al-injaz:short-tests:v1'))).toContain('محتوى محفوظ');
  await page.reload();
  if (info.project.name === 'phone') await page.getByRole('button', {name:/عرض الأقسام/}).click();
  await page.getByRole('button', {name:'الاختبارات والتحصيل', exact:true}).click();
  await section.getByText('اختبار قديم · معلم تجريبي').click();
  await expect(section.getByText('مراجعة الاختبار: تمت المراجعة')).toBeVisible();
  await expect(section.getByLabel('إرفاق نسخة الاختبار')).toBeAttached();
  await expect(section.getByLabel('إرفاق التحليل')).toBeAttached();
  if (info.project.name === 'phone') await page.getByRole('button', {name:/عرض الأقسام/}).click();
  await page.getByRole('button', {name:'الرئيسية', exact:true}).click();
  const backupTools = page.locator('.app-backup-tools');
  await backupTools.locator('summary').click();
  const pending = page.waitForEvent('download');
  await backupTools.getByRole('button', {name:'تنزيل نسخة كاملة'}).click();
  const download = await pending;
  const path = info.outputPath('simplified-backup.json');
  await download.saveAs(path);
  const backup = JSON.parse(await readFile(path, 'utf8'));
  expect(backup.localData['nabd-al-injaz:short-tests:v1']).toContain('محتوى محفوظ');
  expect(JSON.parse(backup.localData['nabd-al-injaz:assessment-tracking:v1'])[0].reviewed).toBe(true);
});
