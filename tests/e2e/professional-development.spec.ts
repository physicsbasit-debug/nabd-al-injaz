import {expect,test} from '@playwright/test';
import {readFile} from 'node:fs/promises';
test('records teacher attendance and restores programme attachments', async ({page,browser}, info) => {
  await page.goto('/');
  await page.evaluate(()=>localStorage.setItem('nabd-al-injaz:schedules:v1',JSON.stringify({teachers:['معلم افتراضي'],lessons:[],verifiedDays:[]})));
  await page.reload();
  if(info.project.name==='phone') await page.getByRole('button',{name:/عرض الأقسام/}).click();
  await page.getByRole('button',{name:'الإنماء المهني',exact:true}).click();
  const section=page.getByRole('region',{name:'الإنماء المهني للمعلمين'});
  await section.getByLabel('عنوان البرنامج').fill('مشغل افتراضي');
  await section.getByLabel('التاريخ').fill('2026-11-14');
  await section.getByRole('button',{name:'حفظ البرنامج'}).click();
  await expect(section.getByRole('status')).toContainText('حُفظ البرنامج');
  await section.getByText('مشغل افتراضي').click();
  await section.getByLabel('حضور معلم افتراضي').selectOption('حاضر');
  await section.getByLabel('إرفاق مادة').setInputFiles({name:'material.pdf',mimeType:'application/pdf',buffer:Buffer.from('example')});
  await expect(section.getByText('material.pdf')).toBeVisible();
  if(info.project.name==='phone') await page.getByRole('button',{name:/عرض الأقسام/}).click();
  await page.getByRole('button',{name:'الرئيسية',exact:true}).click();
  const tools=page.locator('.app-backup-tools');await tools.locator('summary').click();
  const pending=page.waitForEvent('download');await tools.getByRole('button',{name:'تنزيل نسخة كاملة'}).click();const download=await pending;
  const path=info.outputPath('professional-backup.json');await download.saveAs(path);
  const backup=JSON.parse(await readFile(path,'utf8'));expect(backup.professionalFiles).toHaveLength(1);
  const context=await browser.newContext();const other=await context.newPage();await other.goto('http://127.0.0.1:4173/');
  const restored=other.locator('.app-backup-tools');await restored.locator('summary').click();other.once('dialog',dialog=>dialog.accept());await restored.locator('input[type=file]').setInputFiles(path);await expect(restored.getByRole('status')).toContainText('استُعيدت بيانات المنظومة');
  const menu=other.getByRole('button',{name:/عرض الأقسام/});if(await menu.isVisible())await menu.click();
  await other.getByRole('button',{name:'الإنماء المهني',exact:true}).click();const panel=other.getByRole('region',{name:'الإنماء المهني للمعلمين'});await panel.getByText('مشغل افتراضي').click();await expect(panel.getByLabel('حضور معلم افتراضي')).toHaveValue('حاضر');await expect(panel.getByText('material.pdf')).toBeVisible();
  const p=other.waitForEvent('download');await panel.getByRole('button',{name:'تنزيل الملف'}).click();const file=await p;const restoredPath=info.outputPath('material.pdf');await file.saveAs(restoredPath);expect(await readFile(restoredPath,'utf8')).toBe('example');await context.close();
});
