import { readFile } from 'node:fs/promises';
import { expect, test } from '@playwright/test';

test('tracks hand-in and analysis separately and backs up both file kinds', async ({ page, browser }, testInfo) => {
  await page.goto('/');
  if (testInfo.project.name === 'phone') await page.getByRole('button', { name: /عرض الأقسام/ }).click();
  await page.getByRole('button', { name: 'الاختبارات والتحصيل', exact: true }).click();
  const panel = page.getByRole('region', { name: 'متابعة الاختبارات والتحليل' });
  await panel.getByLabel('عنوان الاختبار').fill('اختبار افتراضي');
  await panel.getByLabel('المعلم', { exact: true }).fill('معلم افتراضي');
  await panel.getByRole('button', { name: 'حفظ سجل المتابعة' }).click();
  await expect(panel.getByRole('status')).toContainText('حُفظ سجل');
  await panel.getByText('اختبار افتراضي · معلم افتراضي').click();
  await expect(panel.getByText('تسليم الاختبار: لم يُسلّم · تحليل النتائج: لم يُحلّل')).toBeVisible();
  await panel.getByLabel('إرفاق نسخة الاختبار').setInputFiles({ name:'اختبار.pdf', mimeType:'application/pdf', buffer:Buffer.from('%PDF-fake-test') });
  await expect(panel.getByText('اختبار.pdf')).toBeVisible();
  await panel.getByLabel('إرفاق التحليل').setInputFiles({ name:'تحليل.pdf', mimeType:'application/pdf', buffer:Buffer.from('%PDF-fake-analysis') });
  await expect(panel.getByText('تحليل.pdf')).toBeVisible();
  await panel.getByRole('button', { name:'تعديل المتابعة' }).click();
  await panel.getByLabel('تم تسليم الاختبار').check();
  await panel.getByRole('button', { name:'حفظ تعديل المتابعة' }).click();
  await expect(panel.getByText('تسليم الاختبار: تم التسليم · تحليل النتائج: لم يُحلّل')).toBeVisible();
  await page.screenshot({path:testInfo.outputPath('assessment-tracking.png'),fullPage:true});
  if (testInfo.project.name === 'phone') await page.getByRole('button', { name: /عرض الأقسام/ }).click();
  await page.getByRole('button', { name:'الرئيسية', exact:true }).click();
  const backupTools = page.locator('.app-backup-tools');
  await backupTools.locator('summary').click();
  const waitDownload = page.waitForEvent('download');
  await backupTools.getByRole('button', { name:'تنزيل نسخة كاملة' }).click();
  const download = await waitDownload;
  const path = testInfo.outputPath('assessment-backup.json');
  await download.saveAs(path);
  const backup = JSON.parse(await readFile(path, 'utf8'));
  expect(backup.assessmentFiles).toHaveLength(2);
  expect(backup.localData['nabd-al-injaz:assessment-tracking:v1']).toContain('معلم افتراضي');
  await page.evaluate(() => localStorage.setItem('nabd-al-injaz:short-tests:v1', JSON.stringify([{id:'old-review', teacher:'معلم', subject:'فيزياء', title:'مراجعة', grade:'9', items:9, total:15, knowledge:6, application:6, reasoning:3, multipleChoice:3, longAnswer:1, lessons:2, status:'بانتظار المراجعة', notes:''}])));
  const legacy = structuredClone(backup);
  delete legacy.assessmentFiles;
  delete legacy.localData['nabd-al-injaz:assessment-tracking:v1'];
  delete legacy.localData['nabd-al-injaz:short-tests:v1'];
  page.once('dialog', dialog => dialog.accept());
  await backupTools.locator('input[type=file]').setInputFiles({name:'legacy.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(legacy))});
  await expect(backupTools.getByRole('status')).toContainText('استُعيدت بيانات المنظومة');
  expect(await page.evaluate(() => localStorage.getItem('nabd-al-injaz:short-tests:v1'))).toContain('old-review');
  expect(await page.evaluate(() => localStorage.getItem('nabd-al-injaz:assessment-tracking:v1'))).toContain('معلم افتراضي');
  const context = await browser.newContext();
  const restoredPage = await context.newPage();
  await restoredPage.goto('http://127.0.0.1:4173/');
  const restoredTools = restoredPage.locator('.app-backup-tools');
  await restoredTools.locator('summary').click();
  restoredPage.once('dialog', dialog => dialog.accept());
  await restoredTools.locator('input[type=file]').setInputFiles(path);
  await expect(restoredTools.getByRole('status')).toContainText('استُعيدت بيانات المنظومة');
  const restoredMenu = restoredPage.getByRole('button', { name: /عرض الأقسام/ });
  if (await restoredMenu.isVisible()) await restoredMenu.click();
  await restoredPage.getByRole('button', { name:'الاختبارات والتحصيل', exact:true }).click();
  const restored = restoredPage.getByRole('region', { name:'متابعة الاختبارات والتحليل' });
  await restored.getByText('اختبار افتراضي · معلم افتراضي').click();
  await expect(restored.getByText('اختبار.pdf')).toBeVisible();
  await expect(restored.getByText('تحليل.pdf')).toBeVisible();
  await expect(restored.getByText('تسليم الاختبار: تم التسليم · تحليل النتائج: لم يُحلّل')).toBeVisible();
  for (const [index, content] of ['%PDF-fake-test', '%PDF-fake-analysis'].entries()) {
    const pendingFile = restoredPage.waitForEvent('download');
    await restored.getByRole('button', { name:'تنزيل الملف' }).nth(index).click();
    const restoredDownload = await pendingFile;
    const restoredPath = testInfo.outputPath(`restored-${index}.pdf`);
    await restoredDownload.saveAs(restoredPath);
    expect(await readFile(restoredPath, 'utf8')).toBe(content);
  }
  await context.close();
});
