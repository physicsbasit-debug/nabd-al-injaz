export type EvidenceContext = 'task' | 'activity' | 'topic' | 'cover' | 'assessment' | 'review' | 'visit' | 'program';

const byContext: Record<EvidenceContext, string[]> = {
  task: ['تقرير مختصر عن التنفيذ', 'مراسلة أو مستند يثبت إتمام العمل', 'صورة من الناتج عند الحاجة'],
  activity: ['تقرير تنفيذ النشاط', 'صورة أو نموذج من الناتج', 'سجل متابعة أو محضر مرتبط بالنشاط'],
  topic: ['سجل متابعة تنفيذ الدروس', 'توزيع المنهج أو خطة المعالجة', 'ملخص متابعة الموضوع'],
  cover: ['جدول الاحتياط والتكليفات المنفذة', 'سجل الغياب أو التغطية', 'مراسلة التكليف عند توفرها'],
  assessment: ['سجل مراجعة الاختبار أو التسليم', 'نسخة الاختبار المعتمدة', 'تحليل النتائج أو إجراءات المتابعة'],
  review: ['سجل مراجعة الاختبار أو التسليم', 'نسخة تتضمن الملاحظات أو الاعتماد', 'مراسلة المتابعة عند توفرها'],
  visit: ['سجل الزيارة أو مذكرة المتابعة', 'ملاحظات الزيارة والإجراءات المتفق عليها', 'شاهد متابعة لاحق عند توفره'],
  program: ['كشف الحضور', 'تقرير تنفيذ البرنامج', 'صور من التنفيذ أو نماذج أعمال المشاركين'],
};
const patterns: Array<{ match: RegExp; items: string[] }> = [
  { match: /اجتماع|لقاء|لجنة/, items: ['محضر الاجتماع أو القرارات', 'كشف الحضور أو الدعوة', 'مراسلة متابعة القرارات'] },
  { match: /مشغل|ورشة|تدريب|برنامج إنماء/, items: ['تقرير تنفيذ البرنامج', 'كشف الحضور', 'صور من التنفيذ أو نماذج أعمال المشاركين'] },
  { match: /اختبار|تحصيل|نتائج/, items: ['سجل مراجعة الاختبار أو التسليم', 'تحليل النتائج أو إجراءات المتابعة', 'نموذج من العمل المنفذ'] },
  { match: /خطة|خطط/, items: ['نسخة الخطة المعتمدة أو المحدثة', 'سجل متابعة التنفيذ', 'تقرير أو نموذج من النشاط المنفذ'] },
  { match: /زيارة/, items: byContext.visit },
];
export function suggestEvidence(context: EvidenceContext, title: string): string[] {
  if (context === 'task' || context === 'activity') {
    const normalized = title.normalize('NFKC').replace(/[أإآ]/g, 'ا');
    const match = patterns.find(rule => rule.match.test(normalized));
    if (match) return match.items;
  }
  return byContext[context];
}
